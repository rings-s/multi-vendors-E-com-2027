def resolve_language(value: str | None) -> str:
    if value:
        for part in value.split(","):
            code = part.split(";")[0].strip().lower()[:2]
            if code in SUPPORTED_LANGUAGES:
                return code
    return DEFAULT_LANGUAGE


class _SafeDict(dict[str, Any]):
    def __missing__(self, key: str) -> str:
        return ""


def render(message_type: str, language: str, data: dict[str, Any]) -> tuple[str, str]:
    catalog = MESSAGES.get(message_type)
    if catalog is None:
        return message_type, ""
    title, body = catalog.get(language) or catalog[DEFAULT_LANGUAGE]
    values = _SafeDict({k: v for k, v in data.items()})
    if isinstance(values.get("amount"), int):
        values["amount"] = str(halalas_to_sar(values["amount"]))
    if message_type == "delivery_status_changed":
        labels = DELIVERY_STATUS_LABELS.get(language) or DELIVERY_STATUS_LABELS[DEFAULT_LANGUAGE]
        status = str(values.get("status", ""))
        values["status_label"] = labels.get(f"{values.get('method', '')}:{status}") or labels.get(status, status)
    return title.format_map(values), body.format_map(values)
